#[derive(serde::Serialize, serde::Deserialize)]
struct CacheConfigResponse {
    keep_vae_loaded: bool,
    keep_flux_loaded: bool,
    keep_t5_loaded: bool,
    keep_clip_loaded: bool,
    embedding_cache_size: usize,
    idle_timeout_secs: Option<u64>,
}

/// Update cache configuration
#[command]
async fn set_cache_config(
    app_state: State<'_, AppState>,
    keep_vae_loaded: Option<bool>,
    keep_flux_loaded: Option<bool>,
    keep_t5_loaded: Option<bool>,
    keep_clip_loaded: Option<bool>,
    embedding_cache_size: Option<usize>,
    idle_timeout_secs: Option<u64>,
) -> Result<String, String> {
    let cache = app_state.queue_processor.model_cache();
    let mut config = cache.get_config().await;

    // Update only provided fields
    if let Some(v) = keep_vae_loaded {
        config.keep_vae_loaded = v;
    }
    if let Some(v) = keep_flux_loaded {
        config.keep_flux_loaded = v;
    }
    if let Some(v) = keep_t5_loaded {
        config.keep_t5_loaded = v;
    }
    if let Some(v) = keep_clip_loaded {
        config.keep_clip_loaded = v;
    }
    if let Some(v) = embedding_cache_size {
        config.embedding_cache_size = v;
    }
    // For idle_timeout_secs, we need special handling since None means "no timeout"
    // We use 0 to mean "disable timeout"
    if let Some(v) = idle_timeout_secs {
        config.idle_timeout_secs = if v == 0 { None } else { Some(v) };
    }

    cache.set_config(config).await;
    Ok("Cache configuration updated".to_string())
}

/// Apply a cache configuration preset
