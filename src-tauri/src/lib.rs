/// Auto-tag images using the specified backend
///
/// # Arguments
/// * `image_ids` - List of image IDs to tag
/// * `backend` - Optional backend preference ("local" or "claude"). Uses settings default if not provided.
#[command]
async fn auto_tag_images(
    app_state: State<'_, AppState>,
    image_ids: Vec<String>,
    backend: Option<String>,
) -> Result<Vec<vision::TaggingResult>, String> {
    use tracing::{info, warn};

    // Phase 1: Get settings and image paths from database, then release lock
    let (settings, image_paths, mut results, effective_backend) = {
        let db = app_state.inference_db.lock().await;
        let db = db.as_ref().ok_or("Database not initialized")?;

        // Get settings
        let settings = db.get_auto_tag_settings().unwrap_or_default();

        // Determine backend to use
        let requested_backend = backend
            .and_then(|b| b.parse::<vision::TaggingBackend>().ok())
            .unwrap_or(settings.preferred_backend);

        let effective_backend = match requested_backend {
            vision::TaggingBackend::Local => {
                if vision::is_moondream_downloaded() {
                    Some(vision::TaggingBackend::Local)
                } else if settings.is_claude_available() {
                    warn!("Local model not available, falling back to Claude");
                    Some(vision::TaggingBackend::Claude)
                } else {
                    None
                }
            }
            vision::TaggingBackend::Claude => {
                if settings.is_claude_available() {
                    Some(vision::TaggingBackend::Claude)
                } else if vision::is_moondream_downloaded() {
                    warn!("Claude API not available, falling back to local");
                    Some(vision::TaggingBackend::Local)
                } else {
                    None
                }
            }
        };

        let effective_backend = effective_backend
            .ok_or("No tagging backend available. Download Moondream or configure Claude API key.")?;

        let mut results = Vec::with_capacity(image_ids.len());
        let mut image_paths = Vec::new();

        // Get image paths
        for id in &image_ids {
            match db.get_image_by_id(id) {
                Ok(Some(img)) => {
                    if let Some(file_path) = img.file_path {
                        image_paths.push((id.clone(), std::path::PathBuf::from(file_path)));
                    } else {
                        results.push(vision::TaggingResult {
                            image_id: id.clone(),
                            tags: vec![],
                            backend: effective_backend,
                            success: false,
                            error: Some("Image file not available (pending generation)".to_string()),
                        });
                    }
                }
                Ok(None) => {
                    results.push(vision::TaggingResult {
                        image_id: id.clone(),
                        tags: vec![],
                        backend: effective_backend,
                        success: false,
                        error: Some("Image not found".to_string()),
                    });
                }
                Err(e) => {
                    results.push(vision::TaggingResult {
                        image_id: id.clone(),
                        tags: vec![],
                        backend: effective_backend,
                        success: false,
                        error: Some(format!("Database error: {}", e)),
                    });
                }
            }
        }

        (settings, image_paths, results, effective_backend)
    }; // Database lock released here

    info!(
        backend = %effective_backend,
        count = image_paths.len(),
        "Starting auto-tagging"
    );

    // Phase 2: Process images (no database lock held)
    let mut tagging_results: Vec<(String, Result<Vec<vision::TagWithConfidence>, String>)> = Vec::new();

    match effective_backend {
        vision::TaggingBackend::Local => {
            // Use local Moondream model (currently stub)
            use candle_core::Device;
            let device = Device::cuda_if_available(0).unwrap_or(Device::Cpu);

            match vision::MoondreamTagger::new(device) {
                Ok(mut tagger) => {
                    for (image_id, path) in image_paths {
                        info!(image_id = %image_id, path = %path.display(), "Processing image with Moondream");
                        let result = tagger.extract_tags(&path)
                            .map(|mut tags| {
                                info!(tag_count = tags.len(), "Tags extracted successfully");
                                tags.retain(|t| t.confidence >= settings.min_confidence);
                                tags
                            })
                            .map_err(|e| {
                                warn!(error = %e, "Failed to extract tags from image");
                                e.to_string()
                            });
                        tagging_results.push((image_id, result));
                    }
                }
                Err(e) => {
                    warn!(error = %e, "Failed to load Moondream model");
                    // If model loading fails, mark all as failed
                    for (image_id, _) in image_paths {
                        tagging_results.push((image_id, Err(format!("Failed to load model: {}", e))));
                    }
                }
            }
        }
        vision::TaggingBackend::Claude => {
            // Use Claude Vision API
            let api_key = settings.claude_api_key.clone()
                .ok_or("Claude API key not configured")?;

            let tagger = vision::ClaudeTagger::new(api_key);

            for (image_id, path) in image_paths {
                let result = tagger.extract_tags(&path).await
                    .map(|mut tags| {
                        tags.retain(|t| t.confidence >= settings.min_confidence);
                        tags
                    })
                    .map_err(|e| e.to_string());
                tagging_results.push((image_id, result));
            }
        }
    }

    // Phase 3: Save tags to database
    {
        let db = app_state.inference_db.lock().await;
        let db = db.as_ref().ok_or("Database not initialized")?;

        for (image_id, result) in tagging_results {
            match result {
                Ok(tags) => {
                    // Save tags to database
                    if let Err(e) = db.bulk_add_tags_with_category(&image_id, &tags) {
                        warn!(error = %e, "Failed to save tags to database");
                    }

                    results.push(vision::TaggingResult {
                        image_id,
                        tags,
                        backend: effective_backend,
                        success: true,
                        error: None,
                    });
                }
                Err(e) => {
                    results.push(vision::TaggingResult {
                        image_id,
                        tags: vec![],
                        backend: effective_backend,
                        success: false,
                        error: Some(e),
                    });
                }
            }
        }
    }

    info!(
        success_count = results.iter().filter(|r| r.success).count(),
        total = results.len(),
        "Auto-tagging complete"
    );

    Ok(results)
}

