#[command]
async fn add_to_queue(
    app_state: State<'_, AppState>,
    params: queue::GenerationParams,
) -> Result<String, String> {
    // Generate image ID upfront
    let image_id = uuid::Uuid::new_v4().to_string();

    // Get current session ID from settings
    let session_id = {
        let db_guard = app_state.inference_db.lock().await;
        if let Some(db) = db_guard.as_ref() {
            db.get_setting("current_session_id")
                .ok()
                .flatten()
                .unwrap_or_else(|| uuid::Uuid::new_v4().to_string())
        } else {
            uuid::Uuid::new_v4().to_string()
        }
    };

    // Create pending image entry BEFORE queueing job
    {
        let db_guard = app_state.inference_db.lock().await;
        if let Some(db) = db_guard.as_ref() {
            db.create_pending_image(&image_id, &params, &session_id)
                .map_err(|e| format!("Failed to create pending image: {}", e))?;
        }
    }

    // Queue the job with the pre-generated image_id
    let job_id = app_state.queue_manager.add_job_with_image_id(params, image_id.clone()).await;

    // Emit event for new job (both Tauri and WebSocket)
    emit_job_update(&app_state, &job_id, "pending", 0.0, None, None).await;

    Ok(job_id)
}

