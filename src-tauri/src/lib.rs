/// Read generation metadata from a PNG image
///
/// # Arguments
/// * `image_path` - Path to the PNG image file
///
/// # Returns
/// JSON object with generation parameters if metadata is found, null otherwise
#[command]
async fn read_image_metadata(image_path: String) -> Result<Option<serde_json::Value>, String> {
    use inference::metadata::read_png_metadata_from_file;

    let path = std::path::Path::new(&image_path);
    if !path.exists() {
        return Err(format!("File not found: {}", image_path));
    }

    let metadata = read_png_metadata_from_file(path)
        .map_err(|e| format!("Failed to read metadata: {}", e))?;

    match metadata {
        Some(m) => Ok(Some(serde_json::to_value(m).map_err(|e| e.to_string())?)),
        None => Ok(None),
    }
}

