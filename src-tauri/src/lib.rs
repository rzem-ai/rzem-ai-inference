#[derive(serde::Serialize)]
struct ModelAvailability {
    id: String,
    name: String,
    is_downloaded: bool,
    has_quantized: bool,
}

/// Scan HuggingFace cache for available models (transformers only)
#[command]
fn scan_models() -> Result<Vec<models::DiscoveredComponent>, String> {
    let all_components = models::scan_all_components()
        .map_err(|e| format!("Failed to scan models: {}", e))?;

    // Filter to transformers only for this command
    let transformers = all_components
        .into_iter()
        .filter(|c| c.component_type == models::ComponentType::Transformer)
        .collect();

    Ok(transformers)
}

/// Get availability status of all supported models
#[command]
async fn get_available_models(
    app_state: State<'_, AppState>,
) -> Result<Vec<ModelAvailability>, String> {
    use crate::models::ModelPaths;

    // Use shared database from AppState
    let db_guard = app_state.inference_db.lock().await;
    let db = db_guard.as_ref()
        .ok_or_else(|| "Database not initialized".to_string())?;

    let paths = ModelPaths::new(db)
        .map_err(|e| e.to_string())?;

    let bundle_id = paths.bundle_id()
        .unwrap_or("unknown")
        .to_string();

    Ok(vec![
        ModelAvailability {
            id: bundle_id.clone(),
            name: format!("FLUX Bundle: {}", bundle_id),
            is_downloaded: paths.all_files_exist(),
            has_quantized: false, // Quantization is now handled at component level
        },
    ])
}

