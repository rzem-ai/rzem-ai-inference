#[command]
async fn init_database(app_state: State<'_, AppState>, db_path: String) -> Result<String, String> {
    // Create parent directory if it doesn't exist
    if let Some(parent) = std::path::Path::new(&db_path).parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| format!("Failed to create database directory: {}", e))?;
    }

    let db = db::InferenceDb::new(&db_path)
        .map_err(|e| format!("Failed to open database: {}", e))?;

    db.init_schema()
        .map_err(|e| format!("Failed to initialize schema: {}", e))?;


    *app_state.inference_db.lock().await = Some(db);

    // Load model configs into cache
    app_state.model_config_cache.load_all().await
        .map_err(|e| format!("Failed to load model configs: {}", e))?;

    Ok("Database initialized".to_string())
}

/// Generate an image from a text prompt using Flux model
///
/// # Arguments
/// * `prompt` - Text description of image to generate
/// * `steps` - Number of diffusion steps
/// * `width` - Image width in pixels
/// * `height` - Image height in pixels
/// * `seed` - Random seed for generation (-1 for random)
///
/// # Returns
/// File path to the generated image
#[command]
async fn generate_image(
    app_state: State<'_, AppState>,
    prompt: String,
    steps: u32,
    width: u32,
    height: u32,
    seed: i64,
) -> Result<String, String> {
    use crate::inference::{InferenceEngine, FluxPipeline};
    use crate::db::ImageMetadata;
    use std::fs;

    // Get or create inference engine
    let engine = InferenceEngine::new()
        .map_err(|e| format!("Failed to initialize inference engine: {}", e))?;

    let device = engine.get_device().clone();
    let mut pipeline = FluxPipeline::new(device)
        .map_err(|e| format!("Failed to create pipeline: {}", e))?;

    // Generate image using FLUX
    // Convert seed to u64 (negative means use random)
    let seed_u64 = if seed >= 0 { seed as u64 } else { rand::random::<u64>() };
    let result = pipeline.generate(
        &prompt,
        steps as usize,
        width as usize,
        height as usize,
        4.0, // Default guidance for FLUX Schnell
        seed_u64,
        inference::SamplerType::default(),
        inference::SchedulerType::default(),
    ).map_err(|e| format!("Generation failed: {}", e))?;

    // Determine output path
    let home = dirs::home_dir()
        .ok_or_else(|| "Could not determine home directory".to_string())?;
    let output_dir = home.join(".rzem-ai-inference").join("outputs");

    // Create output directory
    fs::create_dir_all(&output_dir)
        .map_err(|e| format!("Failed to create output directory: {}", e))?;

    // Generate filename with timestamp
    let timestamp = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_err(|e| format!("System time error: {}", e))?
        .as_secs();
    let filename = format!("flux_{}_{}.png", timestamp, seed);
    let output_path = output_dir.join(&filename);

    // Save PNG image data
    fs::write(&output_path, &result.image_data)
        .map_err(|e| format!("Failed to write image: {}", e))?;

    // Insert into gallery database
    let db = app_state.inference_db.lock().await;
    if let Some(db) = db.as_ref() {
        let image_id = uuid::Uuid::new_v4().to_string();

        // Calculate file size
        let file_size = std::fs::metadata(&output_path)
            .map(|m| m.len() as i64)
            .unwrap_or(0);

        let metadata = ImageMetadata {
            id: image_id.clone(),
            file_path: Some(output_path.to_string_lossy().to_string()),
            thumbnail_path: None, // Thumbnails are generated by the queue processor
            prompt: prompt.clone(),
            created_at: timestamp as i64,
            width: Some(width as i32),
            height: Some(height as i32),
            file_size: Some(file_size),
            model_name: "flux-schnell".to_string(),
            negative_prompt: None,
            steps: Some(steps as i32),
            cfg_scale: Some(4.0), // Hardcoded guidance for FLUX Schnell
            seed: Some(seed),
            sampler: Some(format!("{:?}", inference::SamplerType::default())),
            generation_time_ms: Some(result.stats.total_ms as i64),
            status: "completed".to_string(),
            session_id: None,
            updated_at: timestamp as i64,
            loras: None,  // No LoRAs in test command
        };
        if let Err(e) = db.insert_image(&metadata) {
            warn!(error = %e, "Failed to insert image into gallery");
        }
        // Store generation stats
        if let Err(e) = db.insert_generation_stats(&image_id, &result.stats) {
            warn!(error = %e, "Failed to insert generation stats");
        }
    }

    Ok(output_path.to_string_lossy().to_string())
}

