/// Download the Moondream vision model for local tagging
#[command]
async fn download_vision_model(
    app_handle: tauri::AppHandle,
    app_state: State<'_, AppState>,
) -> Result<String, String> {
    // Check if download is already in progress
    {
        let mut in_progress = app_state.download_in_progress.lock().await;
        if *in_progress {
            return Err("Download already in progress".to_string());
        }
        *in_progress = true;
    }

    let result = vision::download_moondream(Some(&app_handle))
        .await
        .map(|_| "Vision model downloaded successfully".to_string())
        .map_err(|e| e.to_string());

    // Reset the flag
    *app_state.download_in_progress.lock().await = false;

    result
}

