    // We use 0 to mean "disable timeout"
    if let Some(v) = idle_timeout_secs {
        config.idle_timeout_secs = if v == 0 { None } else { Some(v) };
    }

    cache.set_config(config).await;
    Ok("Cache configuration updated".to_string())
