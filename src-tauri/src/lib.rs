/// Analyze an image using Claude and generate a prompt to recreate it
///
/// # Arguments
/// * `image_data` - Base64-encoded image data (can include data URL prefix)
/// * `media_type` - Optional MIME type. If not provided, will be inferred from data URL.
#[command]
async fn analyze_image_for_prompt(
    image_data: String,
    media_type: Option<String>,
) -> Result<String, String> {
    // Load Claude API key from settings
    let settings = settings::AppSettings::load()
        .map_err(|e| e.to_string())?;

    let api_key = settings.claude_api_key
        .ok_or_else(|| "Claude API key not configured. Please set it in Settings.".to_string())?;

    // Parse image data - handle both raw base64 and data URL formats
    let (base64_data, mime_type) = if image_data.starts_with("data:") {
        // Parse data URL: data:image/png;base64,xxxxx
        let parts: Vec<&str> = image_data.splitn(2, ',').collect();
        if parts.len() != 2 {
            return Err("Invalid data URL format".to_string());
        }

        // Extract MIME type from header
        let header = parts[0];
        let inferred_mime = header
            .strip_prefix("data:")
            .and_then(|s| s.split(';').next())
            .unwrap_or("image/png")
            .to_string();

        (parts[1].to_string(), media_type.unwrap_or(inferred_mime))
    } else {
        // Raw base64 - use provided media type or default
        (image_data, media_type.unwrap_or_else(|| "image/png".to_string()))
    };

    // Call Claude API to analyze the image
    claude::analyze_image_for_prompt(&api_key, &base64_data, &mime_type)
        .await
        .map_err(|e| e.to_string())
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    run_with_config(shared::protocol::RuntimeConfig::local(), None)
}

/// Run the application with a specific configuration
///
/// This is the main entry point that supports different operation modes
pub fn run_with_config(runtime_config: shared::protocol::RuntimeConfig, port: Option<u16>) {
    // Initialize logging (defaults to info level, use RUST_LOG to override)
    init_logging("info");

    let gallery_db = Arc::new(Mutex::new(None));
    let queue_manager = Arc::new(queue::QueueManager::new(1)); // Max 1 concurrent for now

    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_fs::init())
        .setup(move |app| {
            // Get app handle
            let app_handle = app.handle().clone();

            // Create WebSocket state if in server mode
            let ws_state = if runtime_config.mode == shared::protocol::OperationMode::Server {
                Some(Arc::new(server::ws_state::WsState::new()))
            } else {
                None
            };

            // Create client API if in client mode
            let client_api = if runtime_config.mode == shared::protocol::OperationMode::Client {
                if let Some(server_url) = &runtime_config.server_url {
                    let config = client::ClientConfig::new(server_url.clone());
                    Some(Arc::new(client::api::ApiClient::new(config)))
                } else {
                    tracing::error!("Client mode requires server URL");
                    None
                }
            } else {
                None
            };

            // Create processor with app handle (needs its own clone)
            let queue_processor = Arc::new(
                QueueProcessor::new(
                    queue_manager.clone(),
                    gallery_db.clone(),
                    app_handle.clone(),
                    ws_state.clone(),
                ).expect("Failed to create queue processor")
            );

            // Store in managed state
            let app_state = Arc::new(AppState {
                gallery_db: gallery_db.clone(),
                queue_manager: queue_manager.clone(),
                queue_processor: queue_processor.clone(),
                app_handle: app_handle.clone(),
                download_in_progress: Arc::new(Mutex::new(false)),
                runtime_config: runtime_config.clone(),
                ws_state: ws_state.clone(),
                client_api: client_api.clone(),
            });

            app.manage(app_state.as_ref().clone());

            // Start processor
            tauri::async_runtime::spawn({
                let queue_processor = queue_processor.clone();
                async move {
                    queue_processor.start().await;
                }
            });

            // Start server if in server mode
            if runtime_config.mode == shared::protocol::OperationMode::Server {
                let port = port.unwrap_or(8080);
                tauri::async_runtime::spawn({
                    let app_state_for_server = app_state.clone();
                    async move {
                        match server::start_server(app_state_for_server, port, false).await {
                            Ok(addr) => {
                                tracing::info!("Server started at {}", addr);
                            }
                            Err(e) => {
                                tracing::error!("Failed to start server: {}", e);
                            }
                        }
                    }
                });
            }

            Ok(())
        })
        .invoke_handler(tauri::generate_handler![
            health_check,
            get_runtime_config,
            // Client mode commands
            client_add_to_queue,
            client_get_queue_jobs,
            client_get_queue_job,
            client_cancel_queue_job,
            client_get_file_url,
            // Local commands
            init_database,
            generate_image,
            get_gallery_images,
            search_gallery_images,
            toggle_favorite,
            add_image_tag,
            remove_image_tag,
            delete_gallery_image,
            add_to_queue,
            get_queue_jobs,
            get_queue_job,
            cancel_queue_job,
            clear_completed_jobs,
            // Folder commands
            create_folder,
            update_folder,
            delete_folder,
            move_folder,
            get_folder_tree,
            add_images_to_folder,
            remove_images_from_folder,
            get_folder_images,
            get_uncategorized_images,
            // Enhanced tag commands
            get_all_tags,
            update_tag,
            bulk_add_tag,
            bulk_remove_tag,
            delete_tag,
            // Folder reordering
            reorder_folders,
            // Model download commands
            download_flux_schnell,
            download_flux_dev,
            check_models_downloaded,
            get_model_status,
            get_available_models,
            get_component_availability,
            // Settings commands
            get_hf_token,
            set_hf_token,
            get_claude_api_key,
            set_claude_api_key,
            get_fal_key,
            set_fal_key,
            // Image analysis
            analyze_image_for_prompt,
            read_image_metadata,
            // Model cache commands
            get_cache_stats,
            clear_model_cache,
            get_cache_config,
            set_cache_config,
            set_cache_preset,
            // Auto-tagging commands
            check_vision_model_status,
            download_vision_model,
            clear_vision_model_locks,
            get_auto_tag_settings,
            update_auto_tag_settings,
            auto_tag_images,
            // System stats
            get_system_stats,
            // LoRA commands
            get_loras,
            import_lora,
            remove_lora,
            update_lora,
            get_lora_file_info,
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
