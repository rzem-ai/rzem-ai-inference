#[derive(serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
struct ScanResult {
    components_found: usize,
    components_added: usize,
    bundles_created: usize,
}

/// Scan HuggingFace cache and discover all model components and bundles
#[command]
async fn scan_and_discover_models(
    app_state: State<'_, AppState>,
) -> Result<ScanResult, String> {
    use crate::models::{scan_all_components_with_callbacks, BundleBuilder, to_component_record};
    use tracing::{info, error};
    use std::sync::{Arc, Mutex as StdMutex};

    // Skip scan in dev mode if SKIP_SCAN_IN_DEV is set
    // if cfg!(debug_assertions) && std::env::var("SKIP_SCAN_IN_DEV").is_ok() {
    //     info!("⏭️  Skipping model scan (dev mode + SKIP_SCAN_IN_DEV set)");
    //     return Ok(ScanResult {
    //         components_found: 0,
    //         components_added: 0,
    //         bundles_created: 0,
    //     });
    // }

    info!("🔄 ========================================");
    info!("🔄 scan_and_discover_models COMMAND CALLED");
    info!("🔄 ========================================");
    info!("🔄 Starting model scan and discovery process");

    // Emit scan start event
    let _ = app_state.app_handle.emit("model-scan-progress", serde_json::json!({
        "stage": "scanning",
        "message": "Initializing scan...",
        "progress": 0
    }));

    // Shared counters for tracking progress across callbacks
    let total_components = Arc::new(StdMutex::new(0usize));
    let new_components_count = Arc::new(StdMutex::new(0usize));
    let new_bundles_count = Arc::new(StdMutex::new(0usize));

    // Create progress callback to emit UI events
    let app_handle = app_state.app_handle.clone();
    let progress_callback = Box::new(move |current: usize, total: usize, repo_name: &str| {
        info!("📡 Emitting scan progress: [{}/{}] {}", current, total, repo_name);
        let _ = app_handle.emit("model-scan-progress", serde_json::json!({
            "stage": "scanning",
            "message": format!("[{}/{}] Scanning: {}", current, total, repo_name),
            "progress": (current * 100 / total.max(1)) as u8
        }));
    });

    // Create hash progress callback for detailed hash updates
    let app_handle2 = app_state.app_handle.clone();
    let hash_progress_callback = Box::new(move |filename: &str, percent: u8, processed: u64, total: u64| {
        let processed_gb = processed as f64 / 1_000_000_000.0;
        let total_gb = total as f64 / 1_000_000_000.0;
        let _ = app_handle2.emit("model-scan-progress", serde_json::json!({
            "stage": "hashing",
            "message": format!("Computing hash for {} ({}% - {:.1}/{:.1} GB)", filename, percent, processed_gb, total_gb),
            "progress": percent
        }));
    });

    // Create repo skip callback - checks if repo+snapshot already exists in DB
    let db_arc2 = app_state.inference_db.clone();
    let repo_skip_callback = Box::new(move |repo_id: &str, snapshot_hash: &str| -> bool {
        // Get database access
        let db_guard = tokio::runtime::Handle::current().block_on(async {
            db_arc2.lock().await
        });

        let db = match db_guard.as_ref() {
            Some(d) => d,
            None => return false, // If DB not available, don't skip
        };

        // Check if this repo+snapshot has already been scanned
        match db.has_repo_snapshot(repo_id, snapshot_hash) {
            Ok(exists) => {
                if exists {
                    info!("   ✓ Repo {} with snapshot {} already scanned, skipping", repo_id, &snapshot_hash[..8]);
                }
                exists
            }
            Err(e) => {
                warn!("   ⚠ Failed to check repo snapshot: {} - will scan", e);
                false // On error, don't skip
            }
        }
    });

    // Create repo completion callback - called after each repo is scanned
    let db_arc = app_state.inference_db.clone();
    let app_handle3 = app_state.app_handle.clone();
    let total_components_clone = total_components.clone();
    let new_components_clone = new_components_count.clone();
    let new_bundles_clone = new_bundles_count.clone();

    let repo_completion_callback = Box::new(move |repo_name: &str, repo_components: Vec<models::DiscoveredComponent>| {
        let repo_components = models::filter_sharded_components(repo_components);
        info!("🎁 Processing repo: {} with {} components", repo_name, repo_components.len());

        // Update total component count
        {
            let mut total = total_components_clone.lock().unwrap();
            *total += repo_components.len();
        }

        // Emit progress: processing repo
        let _ = app_handle3.emit("model-scan-progress", serde_json::json!({
            "stage": "processing",
            "message": format!("Processing repo: {}", repo_name),
            "progress": 50
        }));

        // Get database access (blocking on async mutex in sync context)
        let db_guard = tokio::runtime::Handle::current().block_on(async {
            db_arc.lock().await
        });

        let db = match db_guard.as_ref() {
            Some(d) => d,
            None => {
                error!("❌ Database not initialized for repo {}", repo_name);
                return;
            }
        };

        // Insert components from this repo
        let mut repo_new_components = 0;
        for comp in &repo_components {
            let record = to_component_record(comp);
            match db.insert_component(&record) {
                Ok(_) => {
                    info!("   ✓ Added component: {} ({})", record.name, record.component_type);
                    repo_new_components += 1;
                }
                Err(e) => {
                    info!("   ⚠ Component exists: {} - {}", record.name, e);
                }
            }
        }

        // Update new components counter
        {
            let mut new_count = new_components_clone.lock().unwrap();
            *new_count += repo_new_components;
        }

        // Create bundles from this repo's components
        info!("   🎁 Creating bundles for repo: {}", repo_name);
        let builder = BundleBuilder::new(repo_components);
        let bundles = builder.auto_create_bundles();

        if !bundles.is_empty() {
            info!("      Found {} potential bundle(s)", bundles.len());
        }

        let mut repo_new_bundles = 0;
        for bundle_def in &bundles {
            // Calculate total VRAM
            let total_vram: i32 = bundle_def.component_map.iter()
                .filter_map(|(_, comp_id)| {
                    db.get_component(comp_id).ok()
                        .and_then(|c| c.vram_mb)
                })
                .sum();

            let is_complete = bundle_def.component_map.len() >= 4; // transformer + t5 + clip + vae
            let bundle_record = bundle_def.to_record(total_vram, is_complete);

            match db.insert_bundle(&bundle_record) {
                Ok(_) => {
                    // Add component relationships
                    for (role, comp_id) in &bundle_def.component_map {
                        let _ = db.add_component_to_bundle(&bundle_record.id, comp_id, role, true, 0);
                    }

                    let completeness = if is_complete { "complete" } else { "incomplete" };
                    let vram_gb = total_vram as f32 / 1000.0;
                    info!("      ✓ Created bundle: {} ({}, ~{:.1} GB VRAM)",
                        bundle_def.name, completeness, vram_gb);

                    repo_new_bundles += 1;
                }
                Err(_) => {
                    // Bundle already exists, skip silently
                }
            }
        }

        // Update new bundles counter
        if repo_new_bundles > 0 {
            let mut new_count = new_bundles_clone.lock().unwrap();
            *new_count += repo_new_bundles;
            info!("   ✓ Created {} bundle(s) for repo {}", repo_new_bundles, repo_name);
        }
    });

    // Run scanner with all callbacks in a blocking task
    // (scanner is sync and uses block_on in callbacks, so it must run in spawn_blocking)
    info!("📡 About to call scanner...");
    let components = tokio::task::spawn_blocking(move || {
        scan_all_components_with_callbacks(
            Some(progress_callback),
            Some(hash_progress_callback),
            Some(repo_completion_callback),
            Some(repo_skip_callback)
        )
    })
    .await
    .map_err(|e| format!("Scanner task panicked: {}", e))?
    .map_err(|e| {
        error!("❌ Scanner failed: {}", e);
        format!("Failed to scan components: {}", e)
    })?;

    // Get final counts from shared state
    let components_count = *total_components.lock().unwrap();
    let new_components = *new_components_count.lock().unwrap();
    let new_bundles = *new_bundles_count.lock().unwrap();

    info!("✅ Model scan and discovery complete");
    info!("   Total components found: {}", components_count);
    info!("   New components added: {}", new_components);
    info!("   Bundles created: {}", new_bundles);

    // Emit completion event
    let _ = app_state.app_handle.emit("model-scan-progress", serde_json::json!({
        "stage": "complete",
        "message": format!("Scan complete: {} components, {} bundles", components_count, new_bundles),
        "progress": 100
    }));

    Ok(ScanResult {
        components_found: components_count,
        components_added: new_components,
        bundles_created: new_bundles,
    })
}

/// Scan a specific directory for model files (not HuggingFace cache)
/// Identifies model types by inspecting file headers
#[command]
async fn scan_directory_for_models(
    app_state: State<'_, AppState>,
    directory_path: String,
    compute_hashes: Option<bool>,
) -> Result<ScanResult, String> {
    use crate::models::{scan_directory_for_models as scan_dir, scan_directory_for_models_fast as scan_dir_fast, to_component_record};
    use std::path::Path;
    use std::sync::{Arc, Mutex as StdMutex};

    let dir_path = Path::new(&directory_path);
    let should_hash = compute_hashes.unwrap_or(false);

    info!("🔄 ========================================");
    info!("🔄 scan_directory_for_models COMMAND CALLED");
    info!("🔄 Directory: {}", directory_path);
    info!("🔄 Compute hashes: {}", should_hash);
    info!("🔄 ========================================");

    // Emit scan start event
    let _ = app_state.app_handle.emit("model-scan-progress", serde_json::json!({
        "stage": "discovering",
        "message": "Discovering model files...",
        "progress": 0
    }));

    // Shared counter for new components
    let new_components_count = Arc::new(StdMutex::new(0usize));

    // Progress callback
    let app_handle = app_state.app_handle.clone();
    let progress_callback = Box::new(move |current: usize, total: usize, filename: &str| {
        let progress = (current * 100 / total.max(1)) as u8;
        let _ = app_handle.emit("model-scan-progress", serde_json::json!({
            "stage": "identifying",
            "message": format!("[{}/{}] Identifying: {}", current, total, filename),
            "progress": progress,
            "filesProcessed": current,
            "filesFound": total
        }));
    });

    // Run the scan (with or without hash computation)
    let components = if should_hash {
        // Hash progress callback
        let app_handle2 = app_state.app_handle.clone();
        let hash_callback = Box::new(move |filename: &str, percent: u8, processed: u64, total: u64| {
            let processed_mb = processed as f64 / 1_000_000.0;
            let total_mb = total as f64 / 1_000_000.0;
            let _ = app_handle2.emit("model-scan-progress", serde_json::json!({
                "stage": "hashing",
                "message": format!("Computing hash: {} ({}% - {:.1}/{:.1} MB)", filename, percent, processed_mb, total_mb),
                "progress": percent
            }));
        });
        scan_dir(dir_path, Some(progress_callback), Some(hash_callback))
    } else {
        scan_dir_fast(dir_path, Some(progress_callback))
    }.map_err(|e| format!("Scan failed: {}", e))?;

    let components_count = components.len();

    if components.is_empty() {
        info!("⚠️  No model components found in directory");
        let _ = app_state.app_handle.emit("model-scan-progress", serde_json::json!({
            "stage": "complete",
            "message": "No model files found",
            "progress": 100
        }));

        return Ok(ScanResult {
            components_found: 0,
            components_added: 0,
            bundles_created: 0,
        });
    }

    // Save components to database and create bundles
    let _ = app_state.app_handle.emit("model-scan-progress", serde_json::json!({
        "stage": "processing",
        "message": "Saving components to database...",
        "progress": 80
    }));

    let db_guard = app_state.inference_db.lock().await;
    let db = db_guard.as_ref()
        .ok_or_else(|| "Database not initialized".to_string())?;

    let components = models::filter_sharded_components(components);

    for component in &components {
        // Convert to database record
        let record = to_component_record(component);

        // Check if component already exists
        if db.get_component(&record.id).is_ok() {
            info!("   - Component already exists: {}", record.name);
            continue;
        }

        // Insert new component
        match db.insert_component(&record) {
            Ok(_) => {
                *new_components_count.lock().unwrap() += 1;
                info!("   ✓ Added new component: {} ({:?})", record.name, component.component_type);
            }
            Err(e) => {
                warn!("   ✗ Failed to save component: {}", e);
            }
        }
    }

    let new_components = *new_components_count.lock().unwrap();

    info!("✅ Directory scan complete");
    info!("   Components found: {}", components_count);
    info!("   New components added: {}", new_components);

    // Emit completion event
    let _ = app_state.app_handle.emit("model-scan-progress", serde_json::json!({
        "stage": "complete",
        "message": format!("Scan complete: {} components found, {} new", components_count, new_components),
        "progress": 100
    }));

    Ok(ScanResult {
        components_found: components_count,
        components_added: new_components,
        bundles_created: 0,
    })
}

